#!/usr/bin/env python3
"""Which stored live-consensus claims still certify, decided at deploy time.

A record's maturity is written by the evidence lane, but the page is rendered by the Pages build,
sometimes days later. In between, the collection behind a live claim can stop -- a method goes
stale or blocked -- and the stored words do not change. So no surface trusts the stored claim on
its own: `_includes/maturity-state.html` renders "Live consensus" only for a page whose url is in
this projection, and renders every other live claim as "Verified reports".

For every generated record that CLAIMS live on any maturity axis (`maturity.claims_live`) this
runs `live_eligibility.evaluate` and lists the permalink of each one that passes. It never lists a
record that does not claim live -- the projection can withdraw a claim, never make one -- and it
never writes a generated record.

FAIL CLOSED, NEVER BLOCK THE DEPLOY. A missing or malformed evidence store, a counted row with no
build, unreadable telemetry or config -- or any failure while evaluating -- writes an EMPTY
projection and exits 0 with a ::warning:: naming it: every live claim then renders as "Verified
reports", which is true of any record that has one. Failing the step instead would freeze the whole
site's HTML, monitoring cards included, at its last build.

GENERATED AT DEPLOY, NEVER COMMITTED. Like the monitoring projection, the answer is a function of
the current time, so a committed copy would be stale by the next build. Absent (a local render, a
fresh checkout), the include treats every claim as uncertified.

Run:  python auxsays/scripts/build_live_eligibility_projection.py
      python auxsays/scripts/build_live_eligibility_projection.py --root DIR --now 2026-10-27T05:41:00Z
"""
from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

# Run as a bare script by pages.yml: `lib` and `patch_collectors` live beside this file.
sys.path.insert(0, str(Path(__file__).resolve().parent))

import yaml  # noqa: E402

from lib import live_eligibility, maturity  # noqa: E402
from lib.patch_identity import MissingBuildIdentity  # noqa: E402
from lib.report_counts import EvidenceStoreError  # noqa: E402
from patch_collectors.base import atomic_write_text  # noqa: E402

AUX = Path(__file__).resolve().parents[1]
OUTPUT_NAME = "live_eligibility.yml"
HEADER = (
    "# GENERATED by auxsays/scripts/build_live_eligibility_projection.py -- do not edit by hand.\n"
    "#\n"
    "# The pages that may render their stored live-consensus claim as live, decided at deploy time.\n"
    "# A claim whose page is not listed renders as Verified reports. Never committed.\n"
)
# What a refusal to READ the inputs looks like -- named in the warning so an unreadable store is
# told apart from a defect. Both fail closed (see main).
INPUT_FAILURES = (EvidenceStoreError, MissingBuildIdentity, OSError, yaml.YAMLError)


def _parse_now(text: str | None) -> datetime:
    if not text:
        return datetime.now(timezone.utc)
    moment = datetime.fromisoformat(text.strip().replace("Z", "+00:00"))
    return moment if moment.tzinfo else moment.replace(tzinfo=timezone.utc)


def certified_urls(inputs: live_eligibility.Inputs, now: datetime) -> list[str]:
    """Permalinks of the records that claim live AND certify. Prints one diagnostic line per claim."""
    exclusive = live_eligibility.exclusive_url_counts(inputs.counted_groups)
    urls: set[str] = set()
    for path, data in inputs.records:
        if not maturity.claims_live(data):
            continue
        decision = live_eligibility.evaluate(data, inputs.counted_groups, emh_rows=inputs.emh_rows,
                                             now=now, thresholds=inputs.thresholds,
                                             exclusive=exclusive)
        permalink = str(data.get("permalink") or "").strip()
        if decision.live and not permalink:
            # The include joins on page.url, which Jekyll takes from the permalink; without one
            # there is nothing to list, so the claim stays uncertified.
            print(f"{path.name}: certified but has no permalink -- not listed")
            continue
        print(f"{path.name}: {'LIVE' if decision.live else 'not live'}"
              + (f" ({', '.join(decision.reasons)})" if decision.reasons else ""))
        if decision.live:
            urls.add(permalink)
    return sorted(urls)


def render(urls: list[str], now: datetime) -> str:
    payload = {"generated_at": now.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
               "urls": urls}
    return HEADER + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True, width=100)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=AUX,
                    help="the site tree to read (default: this repository's auxsays/)")
    ap.add_argument("--output", type=Path, default=None,
                    help=f"where to write (default: <root>/_data/{OUTPUT_NAME})")
    ap.add_argument("--now", default=None, help="ISO-8601 instant to judge freshness at (tests)")
    args = ap.parse_args(argv)
    now = _parse_now(args.now)
    output = args.output or (args.root / "_data" / OUTPUT_NAME)

    # FAIL CLOSED, on reading AND on evaluating. An empty projection costs a live label (every claim
    # reads as Verified reports); a raise here would fail the deploy and freeze the whole site's
    # HTML -- including every monitoring card -- at its last build. So any failure is a warning
    # and an empty list, never a stopped deploy.
    try:
        inputs = live_eligibility.load_inputs(args.root)
        urls = certified_urls(inputs, now)
        claims = sum(1 for _p, data in inputs.records if maturity.claims_live(data))
    except Exception as exc:  # noqa: BLE001 - deliberately broad; see above
        kind = "unreadable input" if isinstance(exc, INPUT_FAILURES) else "evaluation failure"
        print(f"::warning::live eligibility projection is EMPTY ({kind}), so every live claim "
              f"renders as Verified reports: {type(exc).__name__}: {exc}")
        urls, claims = [], 0

    atomic_write_text(output, render(urls, now))
    print(f"Wrote {output}: {len(urls)} of {claims} live claim(s) certified")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
