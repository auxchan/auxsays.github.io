"""The verdict projection: Python's decision for every page whose verdict rests on a reviewed reason
entry, handed to the Liquid gate so that the gate never decides one (GROWTH-3).

WHY IT EXISTS. A reasoned verdict (WAIT, TEST FIRST, a security page's warning panel) is supported
only while its entry passes `lib.verdict_reasons.support_problems`: every cited row counted on that
page with the same URL, two distinct reporters (identical excerpts are one), or an official
confirmation found verbatim in the named record's captured notes. Round 0 of GROWTH-3 re-implemented
that rule in `_includes/patch-verdict-gate.html` as "every cited URL is among the record's
accepted_report_sources" -- only the first clause. Review 1 (D2) reproduced the gap: with OBS
33.0.0's note reworded, `decide` answered TEST FIRST for 32.2.2 and the page still published "WAIT
if you use macOS 27.2"; with one of two rows dropped from an Acrobat entry, `decide` answered
INSUFFICIENT DATA and the page published TEST FIRST. A second copy of a rule is free to disagree,
and it did.

THE FIX IS ONE AUTHORITY. `project` runs `patch_decision.decide` with the entries the counted
evidence store supports and writes, per page, exactly what Python decided -- verdict, scope, rule,
the supported entry ids, the recommendation line and the panel. `build_verdict_projection.py` writes
it to `_data/verdict_projection.yml` at deploy (pages.yml), after the inputs are final and BEFORE
QA and the Jekyll build, so it is computed from the very tree that is rendered. The gate reads the
row for its page's exact identity and prints it. It cannot publish a WAIT or TEST FIRST that is not
in a row, and it has no rule of its own that could add one.

FALLING BACK ON A WITHDRAWAL. An audited withdrawal changes the evidence store; the next deploy's
projection no longer supports the entry, so the page falls back (to INSUFFICIENT DATA, or to the
next supported entry) with no edit to the reason file and no writer blocked. QA warns, naming what
the page now renders.

GENERATED AT DEPLOY, NEVER COMMITTED (git-ignored, like live_eligibility.yml): a committed copy
would go stale the moment a lane changed the evidence. ABSENT (a local render, a fresh checkout),
the gate publishes no WAIT, no TEST FIRST and no panel -- it fails closed. PRESENT, it must equal
`project` over the same tree: `qa_patch_records --publish-strict` reports any difference as an ERROR,
because the page would render something the authority does not decide.

Only pages with at least one supported entry get a row. A page with none decides from the two
official facts (the lifecycle record, Microsoft's stored release type) or is INSUFFICIENT DATA, and
the gate derives those facts itself.

Reads YAML and the evidence store; no network, no collector run.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Iterable, Mapping

import yaml

from . import patch_decision, verdict_reasons

PROJECTION_NAME = "verdict_projection.yml"
SCHEMA_VERSION = 1
HEADER = (
    "# GENERATED by auxsays/scripts/build_verdict_projection.py -- do not edit by hand. Never committed.\n"
    "#\n"
    "# lib/patch_decision.decide's verdict for every page whose verdict rests on a supported reason entry\n"
    "# (_data/verdict_reasons.yml), computed at deploy from this tree's counted evidence. The verdict gate\n"
    "# (_includes/patch-verdict-gate.html) prints these rows and decides no WAIT or TEST FIRST itself.\n"
)
ROW_KEYS = ("url", "verdict", "scope", "rule", "reasons", "body", "panel_heading", "panel_text")
REASONED = (patch_decision.WAIT, patch_decision.TEST_FIRST)


class ProjectionError(ValueError):
    """A projection file that is present but unreadable or malformed."""


def page_key(record: Mapping[str, Any]) -> str:
    """The key the gate builds in Liquid: product_id|update_version|target_build, raw and stripped."""
    return "|".join(verdict_reasons.record_identity(record))


def row_for(decision: patch_decision.Decision, record: Mapping[str, Any]) -> dict[str, Any]:
    """One page's row: what the page renders for a reasoned decision, character for character."""
    count = int(record.get("update_report_count") or 0)
    return {
        "url": str(record.get("permalink") or record.get("url") or "").strip(),
        "verdict": decision.verdict,
        "scope": decision.scope,
        "rule": decision.rule,
        "reasons": [str(e.get("id") or "") for e in decision.reasons],
        "body": patch_decision.public_body(decision, dict(record), count),
        "panel_heading": patch_decision.PANEL_HEADING.get(decision.panel_kind, ""),
        "panel_text": patch_decision.panel_text(decision),
    }


def project(records: Iterable[Mapping[str, Any]],
            counted_by_identity: Mapping[tuple[str, str, str], list[Mapping[str, Any]]],
            reasons: Iterable[Mapping[str, Any]], lifecycle: Iterable[Mapping[str, Any]],
            ) -> tuple[dict[str, Any], dict[str, list[str]]]:
    """(projection, unsupported entries and why). `reasons` and `lifecycle` must already have passed
    their schema checks: a structurally invalid file contributes nothing (fail closed)."""
    records = [r for r in records if isinstance(r, Mapping)]
    reasons = list(reasons or ())
    lifecycle = list(lifecycle or ())
    by_identity = {verdict_reasons.record_identity(r): r for r in records}
    valid, unsupported = verdict_reasons.valid_reasons_by_identity(reasons, counted_by_identity, by_identity)
    pages: dict[str, dict[str, Any]] = {}
    for rec in records:
        mine = valid.get(verdict_reasons.record_identity(rec), [])
        if not mine:
            continue
        decision = patch_decision.decide(dict(rec), valid_reasons=mine, lifecycle=lifecycle)
        pages[page_key(rec)] = row_for(decision, rec)
    return {"schema_version": SCHEMA_VERSION, "pages": dict(sorted(pages.items()))}, unsupported


def load_fact_files(aux_root: Path) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[str]]:
    """(reasons, lifecycle, problems). A malformed file contributes nothing and is named in problems."""
    problems: list[str] = []
    try:
        reasons = verdict_reasons.load_reasons(Path(aux_root) / "_data" / "verdict_reasons.yml")
    except verdict_reasons.FactFileError as exc:
        problems.append(str(exc))
        reasons = []
    try:
        lifecycle = verdict_reasons.load_lifecycle(Path(aux_root) / "_data" / "patch_lifecycle.yml")
    except verdict_reasons.FactFileError as exc:
        problems.append(str(exc))
        lifecycle = []
    if verdict_reasons.schema_errors(reasons):
        problems.append("verdict_reasons.yml has schema errors")
        reasons = []
    if verdict_reasons.lifecycle_errors(lifecycle):
        problems.append("patch_lifecycle.yml has schema errors")
        lifecycle = []
    return reasons, lifecycle, problems


def build(aux_root: Path) -> tuple[dict[str, Any], dict[str, list[str]], list[str]]:
    """The projection for a site tree, from its records, its counted evidence and its fact files.
    Raises on an unreadable evidence store (the caller decides what that means)."""
    from patch_collectors.base import load_front_matter_and_body  # noqa: PLC0415 - offline reader

    from .report_counts import (counted_evidence_rows, load_evidence_store,  # noqa: PLC0415
                                windows_targets_from_front_matter)
    aux_root = Path(aux_root)
    records = []
    for path in sorted((aux_root / "updates" / "generated").glob("*.md")):
        data, _body = load_front_matter_and_body(path)
        if isinstance(data, dict) and data.get("update_entry") is True:
            records.append(data)
    rows = load_evidence_store(aux_root / "_data" / "consensus_evidence.yml")
    groups = counted_evidence_rows(rows, windows_targets=windows_targets_from_front_matter(records))
    reasons, lifecycle, problems = load_fact_files(aux_root)
    projection, unsupported = project(records, groups, reasons, lifecycle)
    return projection, unsupported, problems


def render(projection: Mapping[str, Any]) -> str:
    return HEADER + yaml.safe_dump(dict(projection), sort_keys=False, allow_unicode=True, width=100)


def load(path: Path) -> dict[str, Any] | None:
    """The projection a deploy built, or None when there is none. Present but malformed raises."""
    path = Path(path)
    if not path.is_file():
        return None
    try:
        payload = yaml.safe_load(path.read_text(encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001 - any parse failure is malformed, never "absent"
        raise ProjectionError(f"{path.name}: unreadable YAML: {exc}") from exc
    if not isinstance(payload, dict) or payload.get("schema_version") != SCHEMA_VERSION \
            or not isinstance(payload.get("pages"), dict):
        raise ProjectionError(f"{path.name}: expected schema_version {SCHEMA_VERSION} and a 'pages' mapping")
    return payload


def rendered_verdict(record: Mapping[str, Any], rows: Mapping[str, Any],
                     lifecycle: Iterable[Mapping[str, Any]]) -> tuple[str, str]:
    """(verdict, scope) the gate publishes for this record, given the projection rows it reads.

    The gate's contract, stated in Python so QA can compare it with `decide`: the official facts
    first (an applicable withdrawal, then Microsoft's monthly security classification), then the
    page's projected WAIT / TEST FIRST, else INSUFFICIENT DATA. test_growth3_verdict_policy renders
    the real template against this over the corpus, so the contract and the template cannot part."""
    if patch_decision.lifecycle_for(dict(record), list(lifecycle or ())):
        return patch_decision.AVOID, patch_decision.AVOID_SCOPE
    if patch_decision.is_monthly_security_update(dict(record)):
        return patch_decision.SECURITY_UPDATE, ""
    row = rows.get(page_key(record)) if isinstance(rows, Mapping) else None
    if isinstance(row, Mapping) and row.get("verdict") in REASONED and str(row.get("scope") or "").strip():
        return str(row["verdict"]), str(row["scope"])
    return patch_decision.INSUFFICIENT_DATA, ""


def phrase(verdict: str, scope: str) -> str:
    return f"{verdict} {scope}".strip()
